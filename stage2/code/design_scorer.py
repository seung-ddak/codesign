"""Frozen-pi_theta scorer with lazy, fixed-shape JIT compilation per structure group."""

from pathlib import Path

import jax
import jax.numpy as jp
import numpy as np

from eval_locomotion_policy import EVAL_COMMANDS, load_policy
from locomotion_env import EPISODE_STEPS, LocomotionEnv
from multi_design_env import PER_DESIGN, MultiDesignEnv, structure_key


def memory_gib():
    """Current and peak resident memory on Linux."""
    values = {}
    for line in Path("/proc/self/status").read_text().splitlines():
        if line.startswith(("VmRSS:", "VmHWM:")):
            key, kib, _ = line.split()
            values[key[:-1]] = int(kib) / 2**20
    return values.get("VmRSS", 0.), values.get("VmHWM", 0.)


def log_memory(stage, compiled_groups=0):
    rss, peak = memory_gib()
    print(f"memory {stage}: rss={rss:.2f} GiB peak={peak:.2f} GiB "
          f"compiled_groups={compiled_groups}", flush=True)


class DesignScorer:
    def __init__(self, template_groups, ckpt, slots=1):
        """Keep templates cheap; build and compile only groups generated by DDPO."""
        self.slots = slots
        self.templates = [[g[i % len(g)] for i in range(slots)] for g in template_groups]
        self.keys = [structure_key(g[0][0]) for g in self.templates]
        self.commands = jp.repeat(
            jp.array([[vx, vy, wz, 0.] for _, vx, vy, wz in EVAL_COMMANDS])[:, None, :],
            slots, axis=1)
        self.policy = load_policy(ckpt)
        self.group_cache = {}

    def _group(self, index):
        if index in self.group_cache:
            return self.group_cache[index]

        env = MultiDesignEnv([self.templates[index]], EPISODE_STEPS,
                             hold_command=True, domain_rand=False)
        group = env.groups[0].env.env  # AutoReset(Episode(DesignGroupEnv))
        base = group.designs

        def rollout(designs, command, rng):
            saved = group.designs
            try:
                group.designs = designs
                state = env.reset(jax.random.split(rng, self.slots))
                state = env._merge([state.info["groups"][0].replace(
                    info={**state.info["groups"][0].info, "command": command})])

                def body(carry, key):
                    state, alive, ret = carry
                    state = env.step(state, self.policy(state.obs, key)[0])
                    ret += state.reward * alive
                    alive *= 1. - state.done
                    return (state, alive, ret), None

                zero = jp.zeros(self.slots)
                (_, _, ret), _ = jax.lax.scan(
                    body, (state, jp.ones(self.slots), zero),
                    jax.random.split(rng, EPISODE_STEPS))
                return ret
            finally:
                group.designs = saved

        # 7 commands share one compiled program (vmap), instead of 7 sequential rollouts.
        entry = {"base": base, "rollout": jax.jit(jax.vmap(rollout, in_axes=(None, 0, 0))),
                 "compiled": False}
        self.group_cache[index] = entry
        return entry

    @staticmethod
    def _stacked(base, designs):
        """Replace the first fixed-shape template slots with generated designs."""
        leaves, treedef = jax.tree.flatten(base)
        arrays = [np.array(x) for x in leaves]
        for slot, (choices, parameters) in enumerate(designs):
            kwargs = ({"seed": int(parameters)} if np.isscalar(parameters)
                      else {"uniforms": parameters})
            env = LocomotionEnv(list(choices), hold_command=True, domain_rand=False, **kwargs)
            values = jax.tree.leaves({name: getattr(env, name) for name in PER_DESIGN})
            for array, value in zip(arrays, values):
                array[slot] = np.asarray(value)
        return jax.tree.unflatten(treedef, [jp.asarray(x) for x in arrays])

    def keys_for(self, seed):
        """Same per-command keys as the former sequential loop."""
        return jp.stack([jax.random.fold_in(jax.random.PRNGKey(seed), i)
                         for i in range(len(self.commands))])

    def score(self, designs, seed=0):
        """Return each design's mean return over the unchanged seven commands."""
        by_group = {}
        for position, (choices, _) in enumerate(designs):
            by_group.setdefault(self.keys.index(structure_key(choices)), []).append(position)

        scores = np.full(len(designs), np.nan)
        for group_index, positions in by_group.items():
            entry = self._group(group_index)
            for start in range(0, len(positions), self.slots):
                selected = positions[start:start + self.slots]
                stacked = self._stacked(entry["base"], [designs[i] for i in selected])
                if not entry["compiled"]:
                    log_memory(f"before_group_{group_index}_compile", len(self.group_cache) - 1)
                value = entry["rollout"](stacked, self.commands, self.keys_for(seed))
                value.block_until_ready()
                if not entry["compiled"]:
                    entry["compiled"] = True
                    log_memory(f"after_group_{group_index}_compile", len(self.group_cache))
                scores[selected] = np.asarray(jax.device_get(value))[:, :len(selected)].mean(axis=0)
        return scores
